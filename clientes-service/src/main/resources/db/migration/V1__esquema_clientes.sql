-- Esquema propio de clientes-service. Ningun otro servicio escribe aqui; cuentas-service guarda el cliente_id de cada
-- cuenta como referencia logica (sin FK entre esquemas: cada microservicio es dueno de sus datos).
-- SQL portable entre PostgreSQL 17 y H2 en modo PostgreSQL (las pruebas corren sobre H2).

-- id: el que asigno la migracion (migracion.cliente_migrado) o, para un alta en linea, uno de cliente_alta_seq. Las
-- altas parten en 100001 para no chocar nunca con los ids que el batch asigna a los titulares del legacy.
create table clientes.cliente (
    id             bigint primary key,
    nombre         varchar(120) not null unique,
    edad           int,
    email          varchar(120),
    telefono       varchar(20),
    direccion      varchar(200),
    origen         varchar(12)  not null check (origen in ('MIGRACION', 'ALTA')),
    creado_en      timestamp    not null,
    actualizado_en timestamp    not null,
    version        bigint       not null default 0
);

create sequence clientes.cliente_alta_seq start with 100001;

-- Credenciales de los clientes y ejecutivos. banco-auth las verifica a traves de este servicio; ningun BFF las ve.
create table clientes.usuario (
    id                bigint generated by default as identity primary key,
    usuario           varchar(60)  not null unique,
    password_hash     varchar(100) not null,
    rol               varchar(20)  not null check (rol in ('CLIENTE', 'EJECUTIVO')),
    cliente_id        bigint null references clientes.cliente (id),
    activo            boolean      not null,
    intentos_fallidos int          not null default 0,
    bloqueado_hasta   timestamp    null
);

-- Transactional outbox de las alertas de seguridad: la alerta se guarda en la misma transaccion que bloquea al usuario.
create table clientes.outbox (
    id           bigint generated by default as identity primary key,
    evento_id    varchar(36)   not null unique,
    topico       varchar(80)   not null,
    clave        varchar(40)   not null,
    tipo         varchar(40)   not null,
    payload      varchar(2000) not null,
    creado_en    timestamp     not null,
    publicado_en timestamp
);

create index idx_outbox_pendiente on clientes.outbox (publicado_en, id);
