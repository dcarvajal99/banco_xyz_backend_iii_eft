-- Esquema propio de cuentas-service. El esquema migracion lo escribe el batch y aqui solo se lee (cierre_cuenta,
-- movimientos y reportes). cliente_id es una referencia logica al cliente de clientes-service: sin FK entre esquemas,
-- porque cada microservicio es dueno de sus datos. Ambos copian el mismo id desde el maestro de la migracion.
-- SQL portable entre PostgreSQL 17 y H2 en modo PostgreSQL (las pruebas corren sobre H2).

-- id = cuenta_id del legacy (101-150) o, para una cuenta abierta en linea, uno de cuenta_seq (desde 200001).
-- cliente_id null cuando el titular llego como "Sin identificar" en el archivo legacy.
create table cuentas.cuenta (
    id                      bigint primary key,
    cliente_id              bigint null,
    titular                 varchar(120)   not null,
    tipo                    varchar(20)    not null check (tipo in ('ahorro', 'prestamo', 'hipoteca')),
    alias                   varchar(40),
    estado                  varchar(12)    not null check (estado in ('ACTIVA', 'BLOQUEADA', 'CERRADA')),
    origen                  varchar(12)    not null check (origen in ('MIGRACION', 'APERTURA')),
    -- Red final: ninguna combinacion de errores de aplicacion puede dejar un saldo negativo.
    saldo_disponible        numeric(18, 2) not null check (saldo_disponible >= 0),
    saldo_cierre            numeric(18, 2) not null,
    tasa_mensual            numeric(8, 5)  not null,
    interes_cierre          numeric(18, 2) not null,
    anomalia                boolean        not null,
    observacion             varchar(255),
    cierre_job_execution_id bigint         null,
    abierta_en              timestamp      not null,
    cerrada_en              timestamp      null,
    motivo_cierre           varchar(120)   null,
    version                 bigint         not null default 0,
    actualizada_en          timestamp      not null
);

create index idx_cuenta_cliente on cuentas.cuenta (cliente_id);
create sequence cuentas.cuenta_seq start with 200001;

-- El numero de tarjeta nunca se guarda en claro: numero_hash = HMAC-SHA256(pepper, PAN).
create table cuentas.tarjeta (
    id                bigint generated by default as identity primary key,
    numero_hash       varchar(64)    not null unique,
    ultimos4          varchar(4)     not null,
    cuenta_id         bigint         not null references cuentas.cuenta (id),
    pin_hash          varchar(100)   not null,
    intentos_fallidos int            not null default 0,
    bloqueada         boolean        not null default false,
    limite_diario     numeric(18, 2) not null
);

-- Movimientos en linea (retiros, transferencias, depositos, pagos). unique (canal, clave): ninguno se aplica dos veces.
create table cuentas.operacion (
    id                 bigint generated by default as identity primary key,
    cuenta_id          bigint         not null references cuentas.cuenta (id),
    tarjeta_id         bigint null references cuentas.tarjeta (id),
    tipo               varchar(20)    not null,
    canal              varchar(20)    not null,
    monto              numeric(18, 2) not null check (monto > 0),
    saldo_resultante   numeric(18, 2) not null,
    terminal_id        varchar(40),
    descripcion        varchar(120),
    referencia         varchar(36),
    clave_idempotencia varchar(80)    not null,
    huella_solicitud   varchar(64)    not null,
    creada_en          timestamp      not null,
    constraint uk_operacion_canal_clave unique (canal, clave_idempotencia)
);

create index idx_operacion_tarjeta_fecha on cuentas.operacion (tarjeta_id, creada_en);
create index idx_operacion_cuenta_fecha on cuentas.operacion (cuenta_id, creada_en);

-- Resultado de cada solicitud de pagos-service aplicada aqui (una fila por pago): auditoria y respuesta idempotente.
create table cuentas.pago_aplicado (
    pago_id        varchar(36)    primary key,
    operacion      varchar(20)    not null check (operacion in ('TRANSFERENCIA', 'DEPOSITO', 'PAGO_SERVICIO')),
    cliente_id     bigint         not null,
    cuenta_origen  bigint,
    cuenta_destino bigint,
    monto          numeric(18, 2) not null check (monto > 0),
    resultado      varchar(12)    not null check (resultado in ('COMPLETADA', 'RECHAZADA')),
    motivo         varchar(40),
    aplicado_en    timestamp      not null
);

-- Consumidor idempotente: Kafka entrega al menos una vez; un evento ya procesado se ignora.
create table cuentas.evento_procesado (
    evento_id    varchar(36) primary key,
    tipo         varchar(40) not null,
    procesado_en timestamp   not null
);

-- Transactional outbox: el evento se guarda en la misma transaccion que el cambio de saldo (o el bloqueo de una
-- tarjeta) y un publicador lo envia a Kafka despues.
create table cuentas.outbox (
    id           bigint generated by default as identity primary key,
    evento_id    varchar(36)   not null unique,
    topico       varchar(80)   not null,
    clave        varchar(40)   not null,
    tipo         varchar(40)   not null,
    payload      varchar(2000) not null,
    creado_en    timestamp     not null,
    publicado_en timestamp
);

create index idx_outbox_pendiente on cuentas.outbox (publicado_en, id);
