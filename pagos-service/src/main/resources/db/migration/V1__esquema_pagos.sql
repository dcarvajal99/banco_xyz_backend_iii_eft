-- Esquema propio de pagos-service: nadie mas escribe aqui. SQL portable entre PostgreSQL 17 y H2.

-- Cada pago, transferencia o deposito tal como lo ve el cliente. SOLICITADO -> COMPLETADO | RECHAZADO.
-- unique (cliente, clave): un reintento del cliente con la misma Idempotency-Key no crea otro pago.
create table pagos.pago (
    id                 varchar(36)    primary key,
    operacion          varchar(20)    not null check (operacion in ('TRANSFERENCIA', 'DEPOSITO', 'PAGO_SERVICIO')),
    cliente_id         bigint         not null,
    usuario_id         bigint         not null,
    cuenta_origen      bigint,
    cuenta_destino     bigint,
    convenio           varchar(40),
    monto              numeric(18, 2) not null check (monto > 0),
    estado             varchar(12)    not null check (estado in ('SOLICITADO', 'COMPLETADO', 'RECHAZADO')),
    motivo             varchar(40),
    validacion         varchar(10)    not null check (validacion in ('PREVIA', 'DIFERIDA', 'NO_APLICA')),
    canal              varchar(10)    not null,
    clave_idempotencia varchar(80)    not null,
    creado_en          timestamp      not null,
    actualizado_en     timestamp      not null,
    constraint uk_pago_cliente_clave unique (cliente_id, clave_idempotencia)
);

create index idx_pago_cliente on pagos.pago (cliente_id, creado_en);

-- Historial: cada paso que toco el pago, en orden. Es la traza que ve el cliente.
create table pagos.historial (
    id          bigint generated by default as identity primary key,
    pago_id     varchar(36) not null references pagos.pago (id),
    evento      varchar(40) not null,
    detalle     varchar(120),
    ocurrido_en timestamp   not null
);

create index idx_historial_pago on pagos.historial (pago_id, id);

create table pagos.evento_procesado (
    evento_id    varchar(36) primary key,
    tipo         varchar(40) not null,
    procesado_en timestamp   not null
);

-- Transactional outbox: la solicitud y su evento (o la alerta de fraude) se guardan juntos.
create table pagos.outbox (
    id           bigint generated by default as identity primary key,
    evento_id    varchar(36)   not null unique,
    topico       varchar(80)   not null,
    clave        varchar(40)   not null,
    tipo         varchar(40)   not null,
    payload      varchar(2000) not null,
    creado_en    timestamp     not null,
    publicado_en timestamp
);

create index idx_outbox_pendiente on pagos.outbox (publicado_en, id);
